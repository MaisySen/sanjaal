/// A Bikram Sambat calendar date.
class BsDate {
  const BsDate(this.year, this.month, this.day);
  final int year;
  final int month;
  final int day;

  String get roman => '$day ${monthsRoman[month - 1]} $year';
  String get nepali => '${nepaliDigits('$day')} ${monthsNepali[month - 1]} ${nepaliDigits('$year')}';

  @override
  bool operator ==(Object other) => other is BsDate && other.year == year && other.month == month && other.day == day;

  @override
  int get hashCode => Object.hash(year, month, day);

  @override
  String toString() => '$year-$month-$day';
}

// 1 Baisakh 2083 BS is 14 April 2026 AD (Nepal embassy holiday lists agree).
final _anchorAd = DateTime.utc(2026, 4, 14);
const _anchorYear = 2083;

String nepaliDigits(String s) => s.replaceAllMapped(RegExp(r'[0-9]'), (m) => String.fromCharCode(0x0966 + int.parse(m[0]!)));

int daysInBsMonth(int year, int month) => _monthDays[year]![month - 1];

int _daysInYear(int y) => _monthDays[y]!.fold(0, (a, b) => a + b);

/// Converts a calendar date (the y/m/d parts are used, time is ignored) to Bikram Sambat. Null when out of range.
BsDate? adToBs(DateTime ad) {
  var n = DateTime.utc(ad.year, ad.month, ad.day).difference(_anchorAd).inDays;
  var y = _anchorYear;
  if (n >= 0) {
    while (true) {
      if (!_monthDays.containsKey(y)) return null;
      final len = _daysInYear(y);
      if (n < len) break;
      n -= len;
      y++;
    }
  } else {
    while (n < 0) {
      y--;
      if (!_monthDays.containsKey(y)) return null;
      n += _daysInYear(y);
    }
  }
  var m = 1;
  while (n >= daysInBsMonth(y, m)) {
    n -= daysInBsMonth(y, m);
    m++;
  }
  return BsDate(y, m, n + 1);
}

/// Converts Bikram Sambat to a UTC date. Null when out of range or the day does not exist.
DateTime? bsToAd(int year, int month, int day) {
  if (!_monthDays.containsKey(year) || month < 1 || month > 12 || day < 1 || day > daysInBsMonth(year, month)) return null;
  var n = 0;
  if (year >= _anchorYear) {
    for (var y = _anchorYear; y < year; y++) {
      n += _daysInYear(y);
    }
  } else {
    for (var y = year; y < _anchorYear; y++) {
      n -= _daysInYear(y);
    }
  }
  for (var m = 1; m < month; m++) {
    n += daysInBsMonth(year, m);
  }
  return _anchorAd.add(Duration(days: n + day - 1));
}
